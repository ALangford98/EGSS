	void MarchingCubes::EdgeCorners(int edge, int& outA, int& outB)
	{
		edge = glm::clamp(edge, 0, 11);
		outA = s_EdgeCorners[edge][0];
		outB = s_EdgeCorners[edge][1];
	}

	glm::ivec3 MarchingCubes::CornerOffset(int corner)
	{
		return s_Corners[glm::clamp(corner, 0, 7)];
	}

	// Hangs a wall off every open edge of the mesh, straight down.
	//
	// An edge used by exactly one triangle is on the boundary of an open
	// surface -- which for a chunk is precisely where it was cut off at the
	// chunk border, and precisely where a neighbour on a different stride
	// leaves a gap. Edges used twice are interior and get nothing.
	//
	// The winding of the single triangle that owns an edge tells us which way
	// is outward, so the skirt quad can be wound to match rather than guessed.
	static void AddSkirt(MeshData& data, float depth)
	{
		if (depth <= 0.0f || data.Indices.size() < 3)
			return;

		// Key on the *positions*, not the indices: marching cubes emits its
		// vertices per triangle, so two triangles sharing an edge in space do
		// not share an index and a by-index count would call every edge a
		// boundary.
		auto key = [](const glm::vec3& a, const glm::vec3& b)
		{
			auto q = [](float v) { return (long long)std::llround(v * 4096.0); };

			long long ax = q(a.x), ay = q(a.y), az = q(a.z);
			long long bx = q(b.x), by = q(b.y), bz = q(b.z);

			// Order-independent, so an edge and its reverse hash together.
			if (std::tie(ax, ay, az) > std::tie(bx, by, bz))
			{
				std::swap(ax, bx); std::swap(ay, by); std::swap(az, bz);
			}

			size_t h = 1469598103934665603ull;
			for (long long v : { ax, ay, az, bx, by, bz })
			{
				h ^= (size_t)v;
				h *= 1099511628211ull;
			}
			return h;
		};

		struct Edge { glm::vec3 A, B; int Count; };
		std::unordered_map<size_t, Edge> edges;

		size_t triangles = data.Indices.size() / 3;

		for (size_t t = 0; t < triangles; t++)
		{
			const glm::vec3& p0 = data.Vertices[data.Indices[t * 3 + 0]].Position;
			const glm::vec3& p1 = data.Vertices[data.Indices[t * 3 + 1]].Position;
			const glm::vec3& p2 = data.Vertices[data.Indices[t * 3 + 2]].Position;

			const glm::vec3 pairs[3][2] = { { p0, p1 }, { p1, p2 }, { p2, p0 } };

			for (const auto& e : pairs)
			{
				size_t k = key(e[0], e[1]);
				auto it = edges.find(k);

				if (it == edges.end())
					edges.insert({ k, Edge{ e[0], e[1], 1 } });
				else
					it->second.Count++;
			}
		}

		for (const auto& entry : edges)
		{
			if (entry.second.Count != 1)
				continue;

			const glm::vec3& a = entry.second.A;
			const glm::vec3& b = entry.second.B;

			glm::vec3 down(0.0f, -depth, 0.0f);

			// Normal along the edge, horizontal and outward-ish. A vertical
			// edge would give a degenerate normal, so those are skipped --
			// they have no gap to close anyway.
			glm::vec3 along = b - a;
			glm::vec3 n = glm::cross(along, glm::vec3(0.0f, 1.0f, 0.0f));

			if (glm::length(n) < 1e-6f)
				continue;

			n = glm::normalize(n);

			unsigned int base = (unsigned int)data.Vertices.size();
			data.Vertices.push_back({ a, n, { 0.0f, 0.0f } });
			data.Vertices.push_back({ b, n, { 1.0f, 0.0f } });
			data.Vertices.push_back({ b + down, n, { 1.0f, 1.0f } });
			data.Vertices.push_back({ a + down, n, { 0.0f, 1.0f } });

			data.Indices.push_back(base);
			data.Indices.push_back(base + 1);
			data.Indices.push_back(base + 2);
			data.Indices.push_back(base);
			data.Indices.push_back(base + 2);
			data.Indices.push_back(base + 3);
		}
	}

	MeshData MarchingCubes::Mesh(const VoxelField3D& field,
		const glm::ivec3& min, const glm::ivec3& max, int stride, float skirtDepth)
	{
		MeshData data;

		if (field.Empty())
			return data;

		stride = glm::max(stride, 1);

		// Cells, not lattice points: a cell at (x,y,z) reads lattice points up
		// to (x+stride,y+stride,z+stride), so the last cell starts one stride
		// short of the far edge.
		glm::ivec3 from = glm::max(min, glm::ivec3(0));
		glm::ivec3 to = glm::min(max, field.Size() - glm::ivec3(1));

		for (int z = from.z; z < to.z; z += stride)
		{
			for (int y = from.y; y < to.y; y += stride)
			{
				for (int x = from.x; x < to.x; x += stride)
				{
					float corner[8];
					int index = 0;

					for (int c = 0; c < 8; c++)
					{
						const glm::ivec3& offset = s_Corners[c] * stride;
						corner[c] = field.DistanceAt(x + offset.x, y + offset.y, z + offset.z);

						// Inside is negative, and the bit set means inside.
						if (corner[c] < 0.0f)
							index |= 1 << c;
					}

					unsigned int edges = s_EdgeMasks.Value[index];
					if (edges == 0)
						continue;

					glm::vec3 vertex[12];

					for (int e = 0; e < 12; e++)
					{
						if ((edges & (1u << e)) == 0)
							continue;

						int a = s_EdgeCorners[e][0];
						int b = s_EdgeCorners[e][1];

						// Where the surface crosses, by linear interpolation
						// between the two corner distances. This is the whole
						// reason the field stores a distance: with an occupancy
						// flag t is always 0.5 and the result is a staircase.
						float da = corner[a];
						float db = corner[b];
						float denominator = da - db;

						float t = std::fabs(denominator) > 1e-12f
							? da / denominator
							: 0.5f;

						glm::ivec3 offsetA = s_Corners[a] * stride;
						glm::ivec3 offsetB = s_Corners[b] * stride;

						glm::vec3 pa = field.PositionOf(x + offsetA.x, y + offsetA.y, z + offsetA.z);
						glm::vec3 pb = field.PositionOf(x + offsetB.x, y + offsetB.y, z + offsetB.z);

						vertex[e] = pa + (pb - pa) * glm::clamp(t, 0.0f, 1.0f);
					}

					const signed char* triangles = s_TriTable[index];

					for (int t = 0; triangles[t] != -1 && t < 15; t += 3)
					{
						const glm::vec3& p0 = vertex[triangles[t]];
						const glm::vec3& p1 = vertex[triangles[t + 1]];
						const glm::vec3& p2 = vertex[triangles[t + 2]];

						// Zero-area triangles, dropped rather than emitted.
						//
						// They appear when the surface passes exactly through a
						// lattice point: that corner's distance is exactly zero,
						// so every edge meeting it interpolates to t = 0 and
						// lands on the same place, and a triangle spanning two
						// such edges collapses to a line. Measured on a sphere
						// of radius 3 on a lattice it lands on exactly, that was
						// 96 triangles from 30 such points -- at both 0.5 m and
						// 0.25 m voxels, since both lattices contain the same
						// integer solutions.
						//
						// Exact comparison on purpose: the two edges produce
						// bit-identical positions from the same corner, so there
						// is no tolerance to choose and nothing to tune.
						if (p0 == p1 || p1 == p2 || p0 == p2)
							continue;

						for (int k = 0; k < 3; k++)
						{
							const glm::vec3& position = vertex[triangles[t + k]];

							MeshVertex out;
							out.Position = position;
							out.Normal = field.SampleNormal(position);
							// Planar, from the two horizontal axes. A voxel
							// surface has no natural parameterisation, and
							// triplanar sampling in the shader is the usual
							// answer -- this is enough for a solid colour or a
							// tiled texture on mostly-flat ground.
							out.TexCoord = { position.x * 0.25f, position.z * 0.25f };

							data.Indices.push_back((unsigned int)data.Vertices.size());
							data.Vertices.push_back(out);
						}
					}
				}
			}
		}

		AddSkirt(data, skirtDepth);

		return data;
	}

