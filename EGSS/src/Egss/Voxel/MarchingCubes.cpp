		struct EdgeMasks
		{
			unsigned int Value[256] = {};

			EdgeMasks()
			{
				for (int i = 0; i < 256; i++)
				{
					unsigned int mask = 0;
					for (int e = 0; s_TriTable[i][e] != -1 && e < 16; e++)
						mask |= 1u << s_TriTable[i][e];

					Value[i] = mask;
				}
			}
		};

